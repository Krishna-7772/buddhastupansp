const BASE = import.meta.env.BASE_URL || '/';
const resolveAsset = (url) => (typeof url === 'string' && url.startsWith('/') ? `${BASE.replace(/\/$/, '')}${url}` : url);

function resolveMediaUrls(obj) {
  if (Array.isArray(obj)) {
    return obj.map(resolveMediaUrls);
  }
  if (obj && typeof obj === 'object') {
    const res = {};
    for (const key of Object.keys(obj)) {
      if (key === 'src' || key === 'poster') {
        res[key] = resolveAsset(obj[key]);
      } else {
        res[key] = resolveMediaUrls(obj[key]);
      }
    }
    return res;
  }
  return obj;
}

